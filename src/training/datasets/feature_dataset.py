from pathlib import Path
import pandas as pd
import soundfile as sf
import torch
from torch.utils.data import Dataset

from src.training.utils.processor_loader import load_whisper_processor


class WhisperFeatureDataset(Dataset):
    """
    Dataset that converts standardized audio + transcript text
    into Whisper-ready training inputs.

    Why this class is needed:
    The earlier AudioTranslationDataset returned raw waveform and plain text.
    That was useful for debugging the data layer.

    But model training needs:
    - input_features: numerical audio features generated by Whisper processor
    - labels: tokenized transcript IDs

    This class performs that conversion.
    """

    def __init__(
        self,
        manifest_path: str,
        language: str = "en",
        task: str = "transcribe",
        split: str = None,
    ):
        """
        Initialize the dataset.

        Parameters:
            manifest_path: path to manifest_standardized.csv
            language: language code for Whisper tokenizer settings
            task: Whisper task, usually 'transcribe' or 'translate'

        Why these parameters matter:
        - language tells Whisper what language the transcript belongs to
        - task controls whether the model is expected to transcribe
          or translate
        """
        self.manifest_path = Path(manifest_path)

        if not self.manifest_path.exists():
            raise FileNotFoundError(f"Manifest not found: {self.manifest_path}")

        self.df = pd.read_csv(self.manifest_path)
        
        if split:
            self.df = self.df[self.df["split"] == split].reset_index(drop=True) 

        required_columns = {
            "language",
            "split",
            "audio_file",
            "audio_path",
            "transcript",
            "standardized_audio_path",
            "target_sample_rate",
            "target_channels",
        }

        missing_columns = required_columns - set(self.df.columns)
        if missing_columns:
            raise ValueError(
                f"Manifest is missing required columns: {missing_columns}"
            )

        self.language = language
        self.task = task
        self.processor = load_whisper_processor()

    def __len__(self) -> int:
        """
        Return number of samples.
        """
        return len(self.df)

    def __getitem__(self, index: int) -> dict:
        """
        Return one Whisper-ready training sample.

        Output dictionary:
        - input_features
        - labels
        - transcript
        - language
        - split
        - standardized_audio_path

        Why this is useful:
        This keeps both training tensors and human-readable metadata together,
        which helps debugging and future testing.
        """
        row = self.df.iloc[index]

        audio_path = row["standardized_audio_path"]
        transcript = str(row["transcript"]).strip()
        split = row["split"]
        dataset_language = row["language"]

        if not Path(audio_path).exists():
            raise FileNotFoundError(f"Audio file not found: {audio_path}")

        # Read the standardized WAV file.
        # The standardizer already converted everything to 16 kHz mono WAV,
        # so loading is simpler and more reliable now.
        waveform, sample_rate = sf.read(audio_path)

        # Convert audio into Whisper input features.
        # return_tensors="pt" gives PyTorch tensors directly.
        audio_inputs = self.processor(
            waveform,
            sampling_rate=sample_rate,
            return_tensors="pt",
        )

        # Convert transcript text into token IDs for training labels.
        text_inputs = self.processor.tokenizer(
            transcript,
            return_tensors="pt",
        )

        # audio_inputs.input_features has shape [1, feature_dim, time]
        # We squeeze the batch dimension because Dataset should return one sample.
        input_features = audio_inputs.input_features.squeeze(0)

        # labels has shape [1, seq_len], so remove the leading batch dimension.
        labels = text_inputs.input_ids.squeeze(0)

        return {
            "input_features": input_features,
            "labels": labels,
            "transcript": transcript,
            "language": dataset_language,
            "split": split,
            "standardized_audio_path": audio_path,
        }